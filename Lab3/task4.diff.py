"""
Лабораторная работа 3.4 — численное дифференцирование таблично заданной
функции. ВАРИАНТ 5: узлы 0, 1, 2, 3, 4; y = 0, 1, 1.4142, 1.7321, 2.0;
x* = 2.0.

Точка x* = 2.0 — внутренний узел таблицы (i = 2), поэтому используются
центральные разностные формулы второго порядка точности O(h^2):

    y'(x*) ~ ( y_{i+1} - y_{i-1} ) / (2h),
    y''(x*) ~ ( y_{i+1} - 2*y_i + y_{i-1} ) / h^2.

Для контроля таблица соответствует f(x) = sqrt(x), точные значения:
    f'(x) = 1/(2*sqrt(x)),  f''(x) = -1/(4*x^(3/2)).
Погрешность формул: O(h^2 * f''') и O(h^2 * f'''') соответственно.

Вход: data/task4.txt — узлы, значения, x*.
Запуск: python task4_diff.py [файл]
"""

import math
import sys

from common import read_task4


def find_interval(xs, x_star):
    # Возвращает индекс i такого, что x* совпадает с узлом, либо внутренний
    for i, x in enumerate(xs):
        if abs(x - x_star) < 1e-12:
            return i
    raise ValueError("x* должен совпадать с узлом таблицы "
                     "(таблица задана дискретно)")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "data/task4.txt"
    xs, ys, x_star = read_task4(path)
    i = find_interval(xs, x_star)
    h = xs[i + 1] - xs[i]

    print("Лабораторная работа 3.4 — вариант 5")
    print("1) Исходная таблица значений функции:")
    print("      i        x_i           y_i")
    for k, (x, y) in enumerate(zip(xs, ys)):
        print(f"     {k}   {x:8.4f}   {y:10.5f}")
    print()

    print(f"2) Точка вычисления производных: x* = {x_star:g} "
          f"(узел с индексом i = {i})")
    print()

    used = [xs[i - 1], xs[i], xs[i + 1]]
    used_y = [ys[i - 1], ys[i], ys[i + 1]]
    print("3) Узлы таблицы, использованные при вычислении "
          "(соседние с x*):")
    print("     x_%d = %.4f (y = %.5f)" % (i - 1, used[0], used_y[0]))
    print("     x_%d = %.4f (y = %.5f)  <- x*" % (i, used[1], used_y[1]))
    print("     x_%d = %.4f (y = %.5f)" % (i + 1, used[2], used_y[2]))
    print(f"     шаг таблицы h = {h:g}\n")

    dy = (ys[i + 1] - ys[i - 1]) / (2.0 * h)
    d2y = (ys[i + 1] - 2.0 * ys[i] + ys[i - 1]) / (h * h)

    print("4) Значение первой производной (центральная разность):")
    print("     y'(x*) ~ (y_{i+1} - y_{i-1}) / (2h) = "
          f"({ys[i + 1]:.5f} - {ys[i - 1]:.5f}) / (2*{h:g}) = {dy:.6f}")
    print()
    print("5) Значение второй производной (вторая разность):")
    print("     y''(x*) ~ (y_{i+1} - 2*y_i + y_{i-1}) / h^2 = "
          f"({ys[i + 1]:.5f} - 2*{ys[i]:.5f} + {ys[i - 1]:.5f}) / {h:g}^2 "
          f"= {d2y:.6f}")
    print()

    # Контроль: таблица соответствует f(x) = sqrt(x)
    f1 = 1.0 / (2.0 * math.sqrt(x_star))
    f2 = -1.0 / (4.0 * x_star ** 1.5)
    print("Контроль (таблица построена по f(x) = sqrt(x)):")
    print(f"     точное f'(x*)  = {f1:.6f},  погрешность |Δ| = "
          f"{abs(dy - f1):.2e}")
    print(f"     точное f''(x*) = {f2:.6f},  погрешность |Δ| = "
          f"{abs(d2y - f2):.2e}")
    print("     Погрешность центральных формул ~ O(h^2) — при большом шаге h")
    print("     таблицы она существенна; для её уменьшения нужен более мелкий"
          " шаг.")


if __name__ == "__main__":
    main()